"""Write docs/public_api.md: every public name with its home sub-package, signature and summary.

Public means listed in ``behav_utils.__all__`` or in the ``__all__`` of a sub-package below.
``tests/test_public_api.py`` fails when the file is out of date, so a change to a public name or
signature shows up in review. Run from the repository root:

    python docs/gen_public_api.py
"""

from __future__ import annotations

import enum
import importlib
import inspect
import re
from pathlib import Path

PACKAGES = ('config', 'tasks', 'data', 'stats', 'readouts', 'analysis', 'plotting')
OUT = Path(__file__).with_name('public_api.md')
_ADDRESS = re.compile(r' at 0x[0-9a-fA-F]+')

HEADER = """# Public API

Generated by `docs/gen_public_api.py` from the package itself; do not edit by hand.
`tests/test_public_api.py` fails when this file is out of date.

Public means a name in `behav_utils.__all__` or in the `__all__` of one of the sub-packages below.
Every name has one home sub-package; the most used ones can also be imported from `behav_utils`
itself (marked *top level*). Everything else is private: module paths below a sub-package (such as
`behav_utils.readouts.fit`) and names starting with `_` can change without notice. From 1.0 the public
names follow semantic versioning (see the README).

Signatures list the parameters and their defaults. Type annotations are left out, and enums are listed
by their members, because Python 3.11 and later versions print both differently.
"""


def _default(value) -> str:
    if callable(value) and hasattr(value, '__qualname__'):
        return value.__qualname__
    return _ADDRESS.sub('', repr(value))


def signature(obj) -> str:
    """``(a, b=1, *, c=None)``: parameters and defaults, no annotations."""
    try:
        params = list(inspect.signature(obj).parameters.values())
    except (TypeError, ValueError):
        return ''
    kinds = [p.kind for p in params]
    star_needed = inspect.Parameter.KEYWORD_ONLY in kinds and inspect.Parameter.VAR_POSITIONAL not in kinds
    last_positional_only = max((i for i, k in enumerate(kinds) if k is inspect.Parameter.POSITIONAL_ONLY),
                               default=None)
    parts = []
    for i, p in enumerate(params):
        if p.kind is inspect.Parameter.KEYWORD_ONLY and star_needed:
            parts.append('*')
            star_needed = False
        if p.kind is inspect.Parameter.VAR_POSITIONAL:
            parts.append('*' + p.name)
        elif p.kind is inspect.Parameter.VAR_KEYWORD:
            parts.append('**' + p.name)
        elif p.default is inspect.Parameter.empty:
            parts.append(p.name)
        else:
            parts.append(f'{p.name}={_default(p.default)}')
        if i == last_positional_only:
            parts.append('/')
    return '(' + ', '.join(parts) + ')'


def summary(obj) -> str:
    """The first sentence of the object's own docstring ('' for constants and undocumented names)."""
    if inspect.isclass(obj):
        doc = vars(obj).get('__doc__')
    elif callable(obj):
        doc = getattr(obj, '__doc__', None)
    else:
        return ''
    if not doc:
        return ''
    paragraph = []
    for line in inspect.cleandoc(doc).splitlines():
        if not line.strip():
            if paragraph:
                break
            continue
        paragraph.append(line.strip())
    text = ' '.join(paragraph)
    if inspect.isclass(obj) and text.startswith(obj.__name__ + '('):
        return ''
    first = re.split(r'(?<=[.!?])\s', text, maxsplit=1)[0]
    return first if len(first) <= 200 else first[:197].rstrip() + '...'


def entry(name: str, obj, top_level: bool) -> str:
    if inspect.isclass(obj) and issubclass(obj, enum.Enum):
        head = f"enum `{name}`: {', '.join(f'{m.name} = {m.value!r}' for m in obj)}"
    elif inspect.isclass(obj):
        head = f'class `{name}{signature(obj)}`'
    elif callable(obj):
        head = f'`{name}{signature(obj)}`'
    elif isinstance(obj, (tuple, list, frozenset)) and len(obj) <= 12 and all(isinstance(x, str) for x in obj):
        head = f'`{name} = {tuple(obj)!r}`'
    else:
        head = f'`{name}` ({type(obj).__name__})'
    where = ' · *top level*' if top_level else ''
    text = summary(obj)
    return f'- {head}{where}' + (f' — {text}' if text else '')


def render() -> str:
    import behav_utils
    top = set(behav_utils.__all__)
    lines = [HEADER]
    for package in PACKAGES:
        module = importlib.import_module(f'behav_utils.{package}')
        lines.append(f'## behav_utils.{package}\n')
        for name in sorted(module.__all__, key=lambda s: (s.lower(), s)):
            lines.append(entry(name, getattr(module, name), name in top))
        lines.append('')
    return '\n'.join(lines)


def main() -> None:
    OUT.write_text(render())
    print(f'wrote {OUT}')


if __name__ == '__main__':
    main()
